/**
 * Schema migrations, applied in order and recorded in `schema_migrations`.
 * They live in code (not .sql files) so they ship inside the Next.js build:
 * Hostinger Business cannot run npm scripts over SSH, so the app migrates
 * itself on first use. SQL is kept compatible with MySQL 8 and MariaDB 10.6+.
 *
 * Never edit a released migration; add a new one.
 */
export interface Migration {
  id: number;
  name: string;
  statements: string[];
}

export const MIGRATIONS: Migration[] = [
  {
    id: 1,
    name: "initial schema",
    statements: [
      `CREATE TABLE IF NOT EXISTS rate_limits (
  bucket CHAR(64) NOT NULL PRIMARY KEY,
  window_start BIGINT NOT NULL,
  hits INT UNSIGNED NOT NULL,
  INDEX idx_rate_limits_window (window_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
      `CREATE TABLE IF NOT EXISTS favicon_cache (
  site VARCHAR(253) NOT NULL PRIMARY KEY,
  source_url VARCHAR(2048) NOT NULL,
  mime VARCHAR(32) NOT NULL,
  body MEDIUMBLOB NOT NULL,
  fetched_at BIGINT NOT NULL,
  INDEX idx_favicon_cache_fetched (fetched_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
      `CREATE TABLE IF NOT EXISTS usage_counters (
  event VARCHAR(16) NOT NULL PRIMARY KEY,
  total BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    ],
  },
];

export const MIGRATIONS_TABLE = `CREATE TABLE IF NOT EXISTS schema_migrations (
  id INT UNSIGNED NOT NULL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`;

/** The whole schema as one script, for importing through phpMyAdmin. */
export function schemaSql(): string {
  const lines = [
    "-- Justeg database schema. Generated by `npm run db:schema`; do not edit.",
    "",
    `${MIGRATIONS_TABLE};`,
  ];
  for (const migration of MIGRATIONS) {
    lines.push("", `-- ${migration.id}: ${migration.name}`);
    for (const statement of migration.statements) lines.push(`${statement};`);
    lines.push(
      `INSERT IGNORE INTO schema_migrations (id, name) VALUES (${migration.id}, '${migration.name.replace(/'/g, "''")}');`,
    );
  }
  return `${lines.join("\n")}\n`;
}
